// Acceptance of the approved A exploration. Uses only the runner's fresh synthetic stack.
import assert from 'node:assert/strict'
import { aggregateAcademicBlocks } from '../../src/data/academicScheduling.ts'
import { generate, response, json, api, singleCourse } from './helpers.mjs'

export const weekLoadScenarios = [
  ['week-load-overview-detail-and-resource-filters', async ({ page, base, record, capture }) => {
    const proposal = await generate(page, true)
    assert.equal(await page.getByRole('button', { name: 'Detalles de búsqueda', exact: true }).count(), 0)
    await page.getByRole('button', { name: /^Ver avisos/ }).click()
    await page.getByRole('dialog', { name: 'Avisos de la generación' }).waitFor()
    await page.keyboard.press('Escape')
    const blocks = aggregateAcademicBlocks(proposal)
    assert.ok(blocks.length > 20, 'Exercise a dense proposal, not a single class')
    // The section consultation is a content-sized modal; the table keeps its height.
    const section = proposal.pending[0]?.sectionId ?? proposal.sections[0].sectionId
    const rowButton = page.getByRole('table', { name: 'Secciones de la propuesta' }).locator(`tr[data-section-id=${JSON.stringify(section)}]`).first().getByRole('button', { name: /^Inspeccionar sección/ })
    const tablePanel = page.locator('#planning-schedule-content')
    const panelHeight = (await tablePanel.boundingBox()).height
    await rowButton.click()
    const consultation = page.getByRole('dialog', { name: /^Inspector de sección/ })
    await consultation.waitFor()
    assert.ok(Math.abs((await tablePanel.boundingBox()).height - panelHeight) < 1, 'Opening the detail reserves no table height')
    assert.equal(await page.getByRole('separator', { name: 'Redimensionar detalle de sección' }).count(), 0)
    assert.ok((await consultation.boundingBox()).height < 700, 'Sparse detail does not fill the viewport')
    await page.keyboard.press('Tab')
    assert.equal(await consultation.evaluate(el => el.contains(document.activeElement)), true, 'Keyboard focus stays in the modal')
    await capture('section-modal-light')
    await page.keyboard.press('Escape')
    await consultation.waitFor({ state: 'hidden' })
    assert.equal(await rowButton.evaluate(el => el === document.activeElement), true)
    assert.ok(Math.abs((await tablePanel.boundingBox()).height - panelHeight) < 1, 'Closing the detail preserves table height')
    await rowButton.click()
    await consultation.getByRole('button', { name: 'Ver en Semana', exact: true }).click()
    await consultation.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Tabla', exact: true }).click()
    assert.equal(await rowButton.locator('..').locator('..').getAttribute('aria-selected'), 'true', 'View switch preserves section selection')

    await page.getByRole('button', { name: 'Semana', exact: true }).click()
    const week = page.getByRole('region', { name: 'Horario semanal', exact: true })
    const map = page.getByRole('table', { name: 'Carga de bloques por franja' })
    await map.waitFor()
    assert.equal(await week.getAttribute('data-week-mode'), 'load')
    const cells = await map.locator('[data-load-day]').evaluateAll(elements => elements.map(el => ({ day: +el.dataset.loadDay, start: +el.dataset.loadStart, count: +el.dataset.loadCount })))
    for (const cell of cells) {
      // The range ends at max configured availability, so clip the last cell if necessary.
      const expected = blocks.filter(b => b.day === cell.day && b.startMinute < cell.start + 120 && b.endMinute > cell.start)
      assert.equal(cell.count, expected.length, `Exact real proposal load at ${cell.day}/${cell.start}`)
    }
    assert.equal(await week.locator('.planning-week__block').count(), 0, 'No shrunken calendar cards in the overview')
    const cell = cells.find(item => item.count > 0)
    const button = map.locator(`[data-load-day="${cell.day}"][data-load-start="${cell.start}"]`)
    await button.focus()
    await page.keyboard.press('Enter')
    const detail = page.getByRole('region', { name: 'Bloques de la franja seleccionada' })
    await detail.waitFor()
    assert.equal(await detail.locator('[data-week-section-id]').count(), cell.count)
    await page.getByRole('button', { name: 'Cerrar franja', exact: true }).click()
    await detail.waitFor({ state: 'hidden' })
    assert.equal(await button.evaluate(el => el === document.activeElement), true)
    await button.click()
    const firstCard = detail.locator('[data-week-section-id]').first()
    const id = await firstCard.getAttribute('data-week-section-id')
    await firstCard.click()
    const editor = page.locator('#academic-scheduling-manual-editor')
    await editor.waitFor()
    assert.equal(await week.getAttribute('data-week-mode'), 'detail')
    assert.equal(await week.locator('.planning-week__block--proposed-preview:visible').count(), 1)
    const startField = page.getByLabel(`Inicio revisión ${id}`, { exact: true })
    const originalStart = await startField.inputValue()
    const before = await json(await page.request.get(`${base}${api}/propuestas/${proposal.proposalId}`))
    await startField.selectOption('0')
    const rejected = response(page, '/ajustes')
    await page.getByRole('button', { name: 'Aplicar ajuste', exact: true }).click()
    assert.equal((await rejected).status(), 422)
    await page.getByRole('alert').filter({ hasText: 'El servidor rechazó el ajuste' }).waitFor()
    assert.deepEqual(await json(await page.request.get(`${base}${api}/propuestas/${proposal.proposalId}`)), before)
    await startField.selectOption(originalStart)
    const accepted = response(page, '/ajustes')
    await page.getByRole('button', { name: 'Aplicar ajuste', exact: true }).click()
    const updated = await json(await accepted)
    await map.waitFor()
    assert.deepEqual(updated, before, 'Reapplying the original placement succeeds without changing its version')
    const fresh = aggregateAcademicBlocks(updated)
    for (const c of cells) assert.equal(await map.locator(`[data-load-day="${c.day}"][data-load-start="${c.start}"]`).getAttribute('data-load-count'), String(fresh.filter(b => b.day === c.day && b.startMinute < c.start + 120 && b.endMinute > c.start).length))
    await page.getByRole('button', { name: 'Cerrar detalle', exact: true }).click()
    await page.locator('#planning-section-detail').waitFor({ state: 'hidden' })
    const teacher = page.getByRole('combobox', { name: 'Filtrar por docente', exact: true })
    const room = page.getByRole('combobox', { name: 'Filtrar por aula', exact: true })
    await teacher.selectOption(fresh[0].teacherId)
    await map.waitFor({ state: 'hidden' })
    assert.equal(await week.locator('[data-week-grid-section-id]').count(), fresh.filter(b => b.teacherId === fresh[0].teacherId).length)
    const widths = await week.locator('[data-week-grid-section-id]').evaluateAll(elements => elements.map(el => el.getBoundingClientRect().width))
    assert.ok(widths.every(width => width >= 150), `Readable lanes: ${widths}`)
    await teacher.selectOption('all')
    const assigned = updated.assignments[0]
    await room.selectOption(assigned.roomId)
    const roomSessionIds = new Set(updated.assignments.filter(item => item.roomId === assigned.roomId).map(item => item.sessionId))
    const expectedRoomBlocks = fresh.filter(b => b.sessionIds.some(sessionId => roomSessionIds.has(sessionId)))
    assert.equal(await week.locator('[data-week-grid-section-id]').count(), expectedRoomBlocks.length)
    await page.getByRole('button', { name: 'Tabla', exact: true }).click()
    assert.equal(await room.inputValue(), assigned.roomId)
    const sectionIds = await page.locator('tr[data-section-id]').evaluateAll(rows => [...new Set(rows.map(row => row.dataset.sectionId))])
    assert.deepEqual(sectionIds.sort(), [...new Set(expectedRoomBlocks.map(b => b.sectionId))].sort())
    await page.getByRole('button', { name: 'Semana', exact: true }).click()
    assert.equal(await room.inputValue(), assigned.roomId)
    await room.selectOption('all')
    await map.waitFor()
    const search = page.getByRole('searchbox', { name: 'Buscar secciones', exact: true })
    await search.fill('SIN-RESULTADOS-DE-PRUEBA')
    assert.equal(await map.locator('[data-load-count]:not([data-load-count="0"])').count(), 0)
    await week.getByRole('status').filter({ hasText: 'No hay bloques' }).waitFor()
    await search.fill('')
    for (const width of [1440, 720, 390, 320]) {
      await page.setViewportSize({ width, height: 900 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, `Reflow ${width}`)
      if (width < 720) {
        const dayButtons = page.getByRole('group', { name: 'Día del mapa de carga' }).getByRole('button')
        await dayButtons.last().click()
        const visibleCells = await map.locator('[data-load-day]:visible').count()
        assert.ok(visibleCells > 0 && visibleCells < cells.length, 'Mobile exposes one day, not a shrunken week')
      }
      await capture(`week-load-${width}`)
    }
    // Test the actual dark tokens on the same load visualization.
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.getByRole('button', { name: /^Cambiar tema de interfaz/ }).first().click()
    await page.getByRole('menuitem', { name: 'Oscuro (Dark)', exact: true }).click()
    await capture('week-load-dark')
    const unassigned = proposal.sections.filter(s => !blocks.some(b => b.sectionId === s.sectionId)).length
    if (unassigned) {
      await page.getByRole('button', { name: `Ver secciones sin horario (${unassigned})`, exact: true }).click()
      assert.equal(await teacher.inputValue(), '__unassigned__')
      await page.getByRole('table', { name: 'Secciones de la propuesta' }).waitFor()
      assert.equal(await page.locator('tr[data-section-id]').evaluateAll(rows => new Set(rows.map(row => row.dataset.sectionId)).size), unassigned)
    }
    record({ blocks: blocks.length, cellsChecked: cells.length, unassigned, resourceLaneMinWidth: Math.min(...widths), checks: 'keyboard drill-down/close, existing editor 422 and 200, exact recounted load, shared room filter, empty search, reflow 320–1440, 720 effective layout at 200% of 1440, dark' })
  }],
  ['week-load-recounts-after-valid-move', async ({ page, base, record }) => {
    await singleCourse(page, base)
    const generationRequest = page.waitForRequest(request => request.method() === 'POST' && new URL(request.url()).pathname.endsWith('/propuestas'))
    const proposal = await generate(page)
    const resources = (await generationRequest).postDataJSON().resources
    const catalog = await json(await page.request.get(`${base}${api}/catalogo`))
    const blocks = aggregateAcademicBlocks(proposal)
    const block = blocks[0]
    assert.ok(block)
    const sessions = proposal.assignments.filter(item => block.sessionIds.includes(item.sessionId)).sort((a, b) => a.startMinute - b.startMinute)
    const covers = (windows, day, start, end) => windows.some(w => w.day === day && w.startMinute <= start && w.endMinute >= end)
    const teacher = (resources?.teachers ?? catalog.teachers).find(t => t.id === block.teacherId)
    const nextDay = [1, 2, 3, 4, 5].find(day => day !== block.day && sessions.every(item =>
      covers(catalog.windows, day, item.startMinute, item.endMinute)
      && covers(teacher.availability, day, item.startMinute, item.endMinute)
      && covers((resources?.rooms ?? catalog.rooms).find(r => r.id === item.roomId).availability, day, item.startMinute, item.endMinute)
    ))
    assert.ok(nextDay, 'A configured alternate weekday exists for this independent synthetic section')
    await page.getByRole('button', { name: 'Semana', exact: true }).click()
    const map = page.getByRole('table', { name: 'Carga de bloques por franja' })
    const cell = map.locator(`[data-load-day="${block.day}"]:not([data-load-count="0"])`).first()
    const start = Number(await cell.getAttribute('data-load-start'))
    const beforeCount = Number(await cell.getAttribute('data-load-count'))
    await cell.click()
    await page.getByRole('region', { name: 'Bloques de la franja seleccionada' }).locator('[data-week-section-id]').first().click()
    await page.getByLabel(`Día revisión ${block.sectionId}`, { exact: true }).selectOption(String(nextDay))
    const pending = response(page, '/ajustes')
    await page.getByRole('button', { name: 'Aplicar ajuste', exact: true }).click()
    const updated = await json(await pending)
    assert.equal(updated.editVersion, (proposal.editVersion ?? 0) + 1)
    await map.waitFor()
    assert.equal(Number(await map.locator(`[data-load-day="${block.day}"][data-load-start="${start}"]`).getAttribute('data-load-count')), beforeCount - 1)
    assert.equal(Number(await map.locator(`[data-load-day="${nextDay}"][data-load-start="${start}"]`).getAttribute('data-load-count')), 1)
    assert.deepEqual(await json(await page.request.get(`${base}${api}/propuestas/${proposal.proposalId}`)), updated)
    record({ acceptedMove: { fromDay: block.day, toDay: nextDay }, editVersion: updated.editVersion, sourceCell: beforeCount - 1, destinationCell: 1 })
  }],
]
